import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

// Generate a standalone workflow: no checkout of the private state or remote code
// downloads. Keep its executable code identical to our regression-tested helpers.
export async function privateBackupWorkflow() {
  const helper=(await readFile(new URL('./private-state-backup.js',import.meta.url),'utf8')).split('if(process.argv[1]')[0].replace("import {pathToFileURL} from 'node:url';\n",'');
  const cloud=(await readFile(new URL('./cloud-private-backup.js',import.meta.url),'utf8')).replace("import {backupState,verifyRestore} from './private-state-backup.js';\n",'');
  const runner=`try {
  const result=await cloudPrivateBackup(process.env);
  const {appendFile}=await import('node:fs/promises');
  await appendFile(process.env.GITHUB_STEP_SUMMARY,'Private backup integrity and no-write restore check passed.\\n\\nReceipt (private repository only): '+result.receiptPath+'\\n\\nNo live state was replaced; no deployment or activation setting was changed.\\n');
  console.log('Private backup and no-write restore check passed. Receipt saved in the private data repository.');
} catch {
  console.error('Backup was NOT verified. Do not activate or deploy. Review repository permissions and writer coordination privately. No response bodies are logged.');
  process.exitCode=1;
}`;
  const body=(helper+'\n'+cloud+'\n'+runner).split('\n').map(line=>line?'          '+line:'').join('\n');
  return `# Generated by scripts/build-private-backup-workflow.js in themeyersgatherings.
# Install ONLY in kasstmaster/themeyersevents-data/.github/workflows/verified-private-backup.yml.
name: Verify private state backup
on:
  workflow_dispatch:
    inputs:
      confirmation:
        description: Creates new private backup and receipt files only; never restores live data
        type: choice
        options:
          - Do not run
          - Create private backup only
        default: Do not run
        required: true
      writers_coordinated:
        description: I have coordinated writers and preserved unsynced drafts for this backup
        type: boolean
        default: false
        required: true
permissions:
  contents: write
concurrency:
  group: verified-private-state-backup
  cancel-in-progress: false
jobs:
  backup:
    if: github.repository == 'kasstmaster/themeyersevents-data' && github.ref == 'refs/heads/main' && inputs.confirmation == 'Create private backup only' && inputs.writers_coordinated == true
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: 24
      - name: Create private backup and verify recovery without restoring live state
        env:
          STATE_REPOSITORY_TOKEN: \${{ github.token }}
          BACKUP_CONFIRM: \${{ inputs.confirmation }}
          WRITERS_COORDINATED: \${{ inputs.writers_coordinated }}
        shell: bash
        run: |
          node --input-type=module <<'PRIVATE_BACKUP_SCRIPT'
${body}
          PRIVATE_BACKUP_SCRIPT
`;
}
if(process.argv[1] && import.meta.url===pathToFileURL(resolve(process.argv[1])).href) {
  await writeFile(resolve(process.argv[2]||'docs/workflows/verified-private-backup.yml'),await privateBackupWorkflow());
}
